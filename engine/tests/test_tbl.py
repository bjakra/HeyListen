"""(HeyListen better-aa) NEON TBL / TBX through the lifter (a64emit.translate, a64_lift.op_text and hot_text) against the
Arm rule written out in tests/tbl_test.c: every form (1-4 table registers, .8B / .16B, TBL / TBX), tables that wrap at v31,
rd the same register as rn, rm or inside the table, on random register files. Built at -march=x86-64-v3 (recomp_tbl's
SSE4.1 shuffle) and -march=x86-64 (its byte loop).

    python -I -B tests/test_tbl.py [--runs 20000]

Teeth (by hand, then restored): the window test's min against 15 made 16: mismatches in every TBL form; the .8B upper
half not cleared: mismatches in the .8B forms only.
Skipped (exit 0) on a host that is not x86-64.
"""
import argparse
import os
import platform
import sys
import tempfile
import time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import test_fpx_sticky as sticky  # noqa: E402  (its compiler search, build and run helpers, the a64-kit paths)

SEED = 20261119


def word(q, rm, regs, tbx, rn, rd):
    return 0x0E000000 | q << 30 | rm << 16 | (regs - 1) << 13 | tbx << 12 | rn << 5 | rd


def guest():
    out = []
    for q in (0, 1):
        for tbx in (0, 1):
            for regs in (1, 2, 3, 4):
                op = "TBX" if tbx else "TBL"
                arr = ".16b" if q else ".8b"
                out.append(("%s%s %d regs" % (op, arr, regs), word(q, 7, regs, tbx, 2, 1)))
                out.append(("%s%s %d regs, wraps at v31" % (op, arr, regs), word(q, 5, regs, tbx, 30, 9)))
                out.append(("%s%s %d regs, rd = rm" % (op, arr, regs), word(q, 4, regs, tbx, 12, 4)))
                out.append(("%s%s %d regs, rd = rn" % (op, arr, regs), word(q, 6, regs, tbx, 20, 20)))
                out.append(("%s%s %d regs, rd in the table, rm = rn" % (op, arr, regs), word(q, 31, regs, tbx, 31, (31 + regs - 1) % 32)))
    return out


def generate(cxx, tmp, flags):
    dll = os.path.join(tmp, "liba64emit.so" if os.name != "nt" else "a64emit.dll")
    sticky.build([cxx, "-std=c++20", "-O0", "-shared", "-Wno-everything", "-o", dll, os.path.join(sticky.KIT, "lift", "a64emit.cpp")]
                 + flags + ([] if os.name == "nt" else ["-fPIC"]), "a64emit")
    import build_emit
    build_emit.build = lambda force=False: dll
    import a64_lift
    import a64_rtgen
    import a64emit
    used = set()
    cases = guest()
    try:
        a64_rtgen.write(tmp)
        lifted, fl = a64emit.translate([(0x1000, w) for _, w in cases])
        if any(fl):
            raise SystemExit("tbl: a64emit did not translate the guest words: %s" % fl)
        lifted = [a64_lift.op_text(t, used) for t in lifted]
    finally:
        if a64emit._lib is not None:
            import _ctypes
            (_ctypes.FreeLibrary if os.name == "nt" else _ctypes.dlclose)(a64emit._lib._handle)
            a64emit._lib = None
    if not all("recomp_tbl(" in t for t in lifted):
        raise SystemExit("tbl: a word was not lifted to recomp_tbl: %s" % [t for t in lifted if "recomp_tbl(" not in t][:1])
    out = ["/* Generated by tests/test_tbl.py from guest words, as a64_lift.py lifts them. */"]
    for i, t in enumerate(lifted):
        out.append("static void g_lifted%d(Ctx *__restrict c) { %s }" % (i, t))
        out.append("static void g_hot%d(Ctx *__restrict c) { %s }" % (i, a64_lift.hot_text(t)))
    out.append("static const struct { const char *name; unsigned word; void (*lifted)(Ctx *), (*hot)(Ctx *); } GUEST[] = {%s};"
               % ", ".join('{"%s", 0x%08xu, g_lifted%d, g_hot%d}' % (n, w, i, i) for i, (n, w) in enumerate(cases)))
    with open(os.path.join(tmp, "tbl_lifted.h"), "w", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    with open(os.path.join(tmp, "a64_fpx.h"), "w", newline="\n") as f:
        f.write(a64_lift.fpx_header(used))


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--runs", type=int, default=20000)
    p.add_argument("--cc")
    p.add_argument("--cxx")
    a = p.parse_args()
    if platform.machine().lower() not in ("x86_64", "amd64"):
        print("tbl: skipped (not an x86-64 host)")
        return
    cc = sticky.compiler(a.cc, "CC", ("clang", "gcc", "cc"), "clang")
    cxx = sticky.compiler(a.cxx, "CXX", ("clang++", "g++", "c++"), "clang++")
    if not cc or not cxx:
        print("tbl: skipped (no compiler)")
        return
    t0 = time.time()
    failed = []
    with tempfile.TemporaryDirectory(prefix="hookshot-tbl-") as tmp:
        generate(cxx, tmp, sticky.target_flags(cxx, tmp))
        for march in ("x86-64-v3", "x86-64"):
            exe = os.path.join(tmp, "tbl_test_%s.exe" % march)
            sticky.build([cc] + sticky.target_flags(cc, tmp) + ["-march=" + march] + sticky.FLAGS +
                         ["-I" + os.path.join(sticky.KIT, "rt"), "-I" + tmp, os.path.join(HERE, "tbl_test.c"),
                          os.path.join(tmp, "a64_suyu.c"), "-o", exe], "the driver at " + march)
            r = sticky.run([exe, str(a.runs), str(SEED)])
            print(r.stdout.rstrip())
            if r.returncode:
                failed.append(march)
    if failed:
        raise SystemExit("tbl: FAIL (%s) in %.1f s" % (", ".join(failed), time.time() - t0))
    print("tbl: pass in %.1f s" % (time.time() - t0))


if __name__ == "__main__":
    main()
